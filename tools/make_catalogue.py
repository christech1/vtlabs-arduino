#!/usr/bin/env python3
"""Build docs/CURRICULUM.md from the header comment of every example sketch.

    python3 tools/make_catalogue.py           write docs/CURRICULUM.md
    python3 tools/make_catalogue.py --check   fail if it is out of date (CI)
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EX = os.path.join(ROOT, "hardware", "vtlabs", "esp32", "libraries", "VTLabsKit", "examples")
OUT = os.path.join(ROOT, "docs", "CURRICULUM.md")
LEVELS = {
    "L1": "Level 1 - Digital input and output",
    "L2": "Level 2 - Analog input, PWM and DAC",
    "L3": "Level 3 - Serial communication: UART, I2C, SPI, RS485",
    "L4": "Level 4 - IoT networking",
    "L5": "Level 5 - Integrated projects",
    "L6": "Level 6 - Matrix keypad",
    "L7": "Level 7 - LED matrix drivers (MAX7219 / WS2812)",
    "L8": "Level 8 - LED matrix, portable API",
    "L9": "Level 9 - Integrated exercises: keypad + matrix + sensors + IoT",
}
REQ_TEXT = {"keypad": "Keypad add-on", "matrix": "LED matrix (any)", "matrix-max7219": "MAX7219 matrix",
            "matrix-ws2812": "WS2812 matrix"}


def fields(text):
    header = text.split("*/", 1)[0]
    out, cur = {}, None
    for line in header.splitlines():
        m = re.match(r"^  ([A-Z][A-Za-z ]+):\s*(.*)$", line)
        if m:
            cur = m.group(1).strip()
            out[cur] = m.group(2).strip()
        elif cur and re.match(r"^\s{6,}\S", line):
            out[cur] += " " + line.strip()
        elif not line.strip():
            cur = None
    return out


def tags(text, name):
    m = re.search(r"@%s:\s*(.+)" % name, text)
    return [t.strip() for t in m.group(1).split(",")] if m else []


def build():
    rows = {}
    for d in sorted(os.listdir(EX)):
        for s in sorted(os.listdir(os.path.join(EX, d))):
            ino = os.path.join(EX, d, s, s + ".ino")
            if not os.path.exists(ino):
                continue
            text = open(ino, encoding="utf-8").read()
            f = fields(text)
            title = re.search(r"VTLabs IoT Training Kit - (.+)", text).group(1).strip()
            req = [REQ_TEXT.get(t, t) for t in tags(text, "requires") if t != "none"]
            opt = [REQ_TEXT.get(t, t) for t in tags(text, "optional")]
            hw = ", ".join(req) or "base kit"
            if opt:
                hw += " (optional: " + ", ".join(opt) + ")"
            libs = f.get("Libraries", "")
            libs = "none" if libs.lower().startswith("none") else libs
            purpose = re.split(r"(?<=\.)\s", f.get("Purpose", ""), maxsplit=1)[0]
            rows.setdefault(s[:2], []).append((s, title, purpose, hw, libs))
    total = sum(len(v) for v in rows.values())
    L = ["# VTLabs IoT Training Kit - Example Curriculum", "",
         "<!-- GENERATED by tools/make_catalogue.py from the example headers - do not edit -->", "",
         f"{total} examples. In the Arduino IDE: select the VTLabs board, then "
         "**File > Examples > VTLabsKit** (under 'Examples for VTLabs IoT Training Kit').", "",
         "Every sketch's header lists purpose, hardware/wiring, libraries, expected behaviour, experiments "
         "and troubleshooting. Add-on lessons need the matching **Tools > Keypad / LED Matrix** setting; "
         "without it they stop with a clear message.", "",
         "Learning outcomes: [learning-outcomes.md](learning-outcomes.md). "
         "Libraries: [libraries.md](libraries.md).", ""]
    for lv in sorted(rows):
        L += [f"## {LEVELS.get(lv, lv)}", "", "| Example | Purpose | Hardware | Libraries |", "|---|---|---|---|"]
        for s, title, purpose, hw, libs in rows[lv]:
            L.append(f"| **{title}**<br>`{s}` | {purpose} | {hw} | {libs} |")
        L.append("")
    return "\n".join(L)


if __name__ == "__main__":
    content = build()
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if "--check" in sys.argv:
        if old != content:
            sys.exit("docs/CURRICULUM.md is out of date - run: python3 tools/make_catalogue.py")
        print("catalogue up to date")
    else:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        print("wrote docs/CURRICULUM.md")
